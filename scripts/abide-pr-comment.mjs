#!/usr/bin/env node
// scripts/abide-pr-comment.mjs
// Post or refresh one sticky abide-judge comment on a PR from the judge JSON.
// Finds an existing comment by its HTML marker and PATCHes it, so re-pushes
// update in place instead of stacking comments.
//
// Usage: node scripts/abide-pr-comment.mjs [--in <judge.json>] [--pr <n>]
// Env:   GITHUB_REPOSITORY (owner/repo), GH_TOKEN, PR_NUMBER.

import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const MARKER = '<!-- abide-judge -->';

function flagValue(argv, name) {
  const i = argv.indexOf(name);
  return i !== -1 && argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[i + 1] : null;
}

function gh(args, inputFile) {
  const full = inputFile ? [...args, '--input', inputFile] : args;
  return execFileSync('gh', full, { encoding: 'utf8' });
}

function cell(value) {
  return String(value ?? '')
    .replace(/\|/g, '\\|')
    .replace(/`/g, '\\`')
    .replace(/[\r\n]+/g, ' ')
    .slice(0, 200);
}

function render(report) {
  const lines = [MARKER, '### abide judge', ''];
  const head = String(report.headSha || '').slice(0, 8);
  const spend = typeof report.spendUsd === 'number' ? ` · $${report.spendUsd.toFixed(4)}` : '';

  if (report.verdict === 'error') {
    lines.push(`**Could not judge** \`${head}\`${spend}.`, '');
    lines.push(`> ${cell(report.error || 'unknown error')}`, '');
    lines.push('_The gate fails closed: re-run once the judge can run._');
    return lines.join('\n');
  }

  const regressions = report.regressions || [];
  const warnings = report.warnings || [];
  const skipped = report.skipped || [];
  const judged = report.judged || [];

  lines.push(
    report.verdict === 'fail'
      ? `**New violations found** in \`${head}\`${spend}.`
      : `**Clear** \`${head}\` — no newly broken rules${spend}.`,
    '',
  );

  if (regressions.length > 0) {
    lines.push('| Rule | File | Band | Was |', '| --- | --- | --- | --- |');
    for (const r of regressions) lines.push(`| \`${cell(r.rule)}\` | \`${cell(r.file)}\` | ${cell(r.band)} | ${cell(r.baseBand)} |`);
    lines.push('');
  }
  if (warnings.length > 0) {
    lines.push(`<details><summary>Newly flagged (advisory, ${warnings.length})</summary>`, '');
    lines.push('| Rule | File | Band |', '| --- | --- | --- |');
    for (const w of warnings) lines.push(`| \`${cell(w.rule)}\` | \`${cell(w.file)}\` | ${cell(w.band)} |`);
    lines.push('', '</details>', '');
  }

  lines.push(
    `<sub>Judged ${judged.length} changed file(s); ${skipped.length} skipped (cap). ` +
      'Ratchet: only rules that got worse than base block. ' +
      'Generated by <code>scripts/abide-pr-judge.mjs</code>.</sub>',
  );
  return lines.join('\n');
}

function findComment(repo, pr) {
  const out = gh([
    'api',
    `repos/${repo}/issues/${pr}/comments`,
    '--paginate',
    '--jq',
    `.[] | select(.body | contains("${MARKER}")) | .id`,
  ]);
  const ids = out.split('\n').map((s) => s.trim()).filter(Boolean);
  return ids.length > 0 ? ids[ids.length - 1] : null;
}

function main() {
  const argv = process.argv.slice(2);
  const repo = process.env.GITHUB_REPOSITORY;
  const pr = flagValue(argv, '--pr') || process.env.PR_NUMBER;
  const inFile = flagValue(argv, '--in') || '.abide/judge.json';

  if (!repo || !pr) {
    console.error('abide-pr-comment: GITHUB_REPOSITORY and PR_NUMBER (or --pr) are required');
    process.exit(2);
  }
  if (!fs.existsSync(path.resolve(inFile))) {
    console.error(`abide-pr-comment: judge report not found at ${inFile}`);
    process.exit(2);
  }

  const report = JSON.parse(fs.readFileSync(path.resolve(inFile), 'utf8'));
  const body = render(report);
  const payloadFile = path.resolve('.abide/judge-comment.json');
  fs.mkdirSync(path.dirname(payloadFile), { recursive: true });
  fs.writeFileSync(payloadFile, JSON.stringify({ body }));

  const existing = findComment(repo, pr);
  if (existing) {
    gh(['api', '-X', 'PATCH', `repos/${repo}/issues/comments/${existing}`], payloadFile);
    console.log(`abide-pr-comment: updated comment ${existing}`);
  } else {
    gh(['api', '-X', 'POST', `repos/${repo}/issues/${pr}/comments`], payloadFile);
    console.log('abide-pr-comment: created sticky comment');
  }
}

main();
