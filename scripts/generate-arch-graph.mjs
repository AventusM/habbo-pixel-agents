#!/usr/bin/env node
// scripts/generate-arch-graph.mjs
// Generates docs/architecture/module-graph.md — a directory-level mermaid
// dependency graph of src/ (plus the web server entry), aggregated from
// per-file edges. Regenerate: npm run arch:graph

import madge from 'madge';
import fs from 'fs';
import path from 'path';

const OUT_DIR = 'docs/architecture';
const OUT_FILE = path.join(OUT_DIR, 'module-graph.md');

// Enumerate src modules (madge's directory mode resolves 0 entries with this
// project's ESM-style imports; explicit entries work reliably)
function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true, recursive: true })
    .filter(e => e.isFile() && /\.(ts|tsx)$/.test(e.name) && !/\.test\./.test(e.name))
    .map(e => path.join(e.parentPath ?? e.path, e.name));
}
const entries = walk('src');

const result = await madge(entries, {
  extensions: ['ts', 'tsx'],
});
const tree = result.obj(); // { file: [deps] }

// Aggregate file edges into feature-cluster edges. The source tree is flat,
// so clusters are derived from filename conventions (this mapping also
// previews the feature-sliced target layout in docs/architecture).
const CLUSTER_RULES = [
  [/^(RoomCanvas|AvatarDebugGrid|LayoutEditorPanel)\./, 'ui-react'],
  [/^(main|webview)\./, 'hosts'],
  [/^(avatar|Avatar|pixelLab)/, 'avatars'],
  [/^agent/, 'agents'],
  [/^kanban/, 'kanban'],
  [/^(azure|github|copilotMonitor|fileWatcher)/, 'integrations'],
  [/^(wsClient|demoData|server)/, 'web-host'],
  [/^(iso|cameraController|sectionManager|roomLayoutEngine|idleWander|teleportEffect|furnitureRegistry|isometricMath)/, 'room-engine'],
  [/^envConfig/, 'env'],
];

function dirOf(file) {
  const base = path.basename(file);
  for (const [re, cluster] of CLUSTER_RULES) {
    if (re.test(base)) return cluster;
  }
  return 'core-misc';
}

const dirEdges = new Map(); // "a -> b" => count
const dirSet = new Set();
for (const [file, deps] of Object.entries(tree)) {
  const from = dirOf(file);
  dirSet.add(from);
  for (const dep of deps) {
    const to = dirOf(dep);
    if (from === to) continue;
    dirSet.add(to);
    const key = `${from}|${to}`;
    dirEdges.set(key, (dirEdges.get(key) ?? 0) + 1);
  }
}

const dirs = [...dirSet].sort();
const short = (d) => d;

const lines = [];
lines.push('# Module dependency graph (directory level)');
lines.push('');
lines.push(`Generated by \`npm run arch:graph\` — do not edit by hand. ${dirs.length} directories, ${Object.keys(tree).length} modules.`);
lines.push('');
lines.push('```mermaid');
lines.push('graph LR;');
for (const d of dirs) {
  lines.push(`  "${short(d)}"["${short(d)}"];`);
}
for (const [key, count] of [...dirEdges.entries()].sort()) {
  const [from, to] = key.split('|');
  const label = count > 1 ? `|${count}|` : '';
  lines.push(`  "${short(from)}" -->|"${short(to)}"| "${short(to)}";`.replace(`-->|"${short(to)}"|`, ` -->${label} `));
}
lines.push('```');
lines.push('');
lines.push('## File-level detail');
lines.push('');
lines.push('<details><summary>Per-file dependency counts</summary>');
lines.push('');
lines.push('| Module | Dependencies |');
lines.push('|---|---|');
for (const file of Object.keys(tree).sort()) {
  lines.push(`| ${file} | ${tree[file].length} |`);
}
lines.push('');
lines.push('</details>');
lines.push('');

fs.mkdirSync(OUT_DIR, { recursive: true });
fs.writeFileSync(OUT_FILE, lines.join('\n'));
console.log(`Wrote ${OUT_FILE}: ${dirs.length} directories, ${dirEdges.size} directory edges, ${Object.keys(tree).length} modules`);
